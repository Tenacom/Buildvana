using System.Text;

namespace Buildvana.Sdk.SourceGenerators.Internal;

/// <summary>
/// Provides extension methods for <see cref="StringBuilder"/>.
/// </summary>
internal static class StringBuilderExtensions
{
    extension(StringBuilder @this)
    {
        public StringBuilder AppendFileHeader()
            => @this.AppendLine("// <auto-generated>")
                    .AppendLine($"// This file was automatically generated by {GeneratorInfo.PackageId}. DO NOT MODIFY!")
                    .AppendLine("// </auto-generated>")
                    .AppendLine()
                    .AppendLine("#nullable enable")
                    .AppendLine();

        public StringBuilder AppendGuestCodeAttributes(string indent, GuestCodeAttributes attributes)
        {
            if (attributes.DebuggerNonUserCode)
            {
                _ = @this.AppendLine($"{indent}[global::System.Diagnostics.DebuggerNonUserCodeAttribute]");
            }

            if (attributes.ExcludeFromCodeCoverage)
            {
                _ = @this.AppendLine($"{indent}[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverageAttribute]");
            }

            if (attributes.GeneratedCode)
            {
                const string arguments = $"\"{GeneratorInfo.PackageId}\", \"{GeneratorInfo.PackageVersion}\"";
                _ = @this.AppendLine($"{indent}[global::System.CodeDom.Compiler.GeneratedCodeAttribute({arguments})]");
            }

            return @this;
        }

        public StringBuilder AppendBooleanAssemblyAttribute(string name, bool? value)
            => value is { } flag
                ? @this.AppendLine($"[assembly:{name}({(flag ? "true" : "false")})]")
                : @this;
    }
}
