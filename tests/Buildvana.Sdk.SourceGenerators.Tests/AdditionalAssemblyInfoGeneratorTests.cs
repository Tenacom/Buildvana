using Buildvana.Sdk.SourceGenerators;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

internal sealed class AdditionalAssemblyInfoGeneratorTests
{
    [Test]
    public async Task BothProperties_GenerateBothAttributes()
    {
        var (_, source, outputCompilation) = RunGenerator(clsCompliant: "true", comVisible: "false");
        await Assert.That(source).StartsWith($"{ExpectedGuestCode.FileHeader}\n\n");
        await Assert.That(source).Contains("[assembly:global::System.CLSCompliant(true)]");
        await Assert.That(source).Contains("[assembly:global::System.Runtime.InteropServices.ComVisible(false)]");
        await TestCompilation.AssertHasNoErrors(outputCompilation).ConfigureAwait(false);
    }

    [Test]
    public async Task MissingProperty_GeneratesNoAttributeForIt()
    {
        var (_, source, outputCompilation) = RunGenerator(clsCompliant: null, comVisible: "true");
        await Assert.That(source).DoesNotContain("CLSCompliant");
        await Assert.That(source).Contains("[assembly:global::System.Runtime.InteropServices.ComVisible(true)]");
        await TestCompilation.AssertHasNoErrors(outputCompilation).ConfigureAwait(false);
    }

    [Test]
    public async Task NoProperties_GenerateHeaderOnly()
    {
        var (_, source, outputCompilation) = RunGenerator(clsCompliant: null, comVisible: null);
        await Assert.That(source.TrimEnd()).IsEqualTo(ExpectedGuestCode.FileHeader);
        await TestCompilation.AssertHasNoErrors(outputCompilation).ConfigureAwait(false);
    }

    [Test]
    public async Task GeneratedFile_HasGeneratedCodeName()
    {
        var (filePath, _, _) = RunGenerator(clsCompliant: null, comVisible: null);
        await Assert.That(Path.GetFileName(filePath)).IsEqualTo("BV_AssemblyAttributes.g.cs");
    }

    [Test]
    public async Task CSharp8_GeneratesNullableDirective()
    {
        var (_, source, outputCompilation) = RunGenerator(clsCompliant: "true", comVisible: "false", LanguageVersion.CSharp8);
        await Assert.That(source).StartsWith($"{ExpectedGuestCode.FileHeader}\n\n");
        await TestCompilation.AssertHasNoErrors(outputCompilation).ConfigureAwait(false);
    }

    [Test]
    public async Task BelowCSharp8_GeneratesNoNullableDirective()
    {
        var (_, source, outputCompilation) = RunGenerator(clsCompliant: "true", comVisible: "false", LanguageVersion.CSharp7_3);
        await Assert.That(source).StartsWith($"{ExpectedGuestCode.AutoGeneratedComment}\n\n[assembly:");
        await Assert.That(source).DoesNotContain("#nullable");
        await TestCompilation.AssertHasNoErrors(outputCompilation).ConfigureAwait(false);
    }

    private static (string FilePath, string Source, Compilation OutputCompilation) RunGenerator(
        string? clsCompliant,
        string? comVisible,
        LanguageVersion languageVersion = LanguageVersion.Latest)
    {
        var globalOptions = new Dictionary<string, string>();
        if (clsCompliant is not null)
        {
            globalOptions["build_property.CLSCompliant"] = clsCompliant;
        }

        if (comVisible is not null)
        {
            globalOptions["build_property.ComVisible"] = comVisible;
        }

        var optionsProvider = new TestAnalyzerConfigOptionsProvider(
            globalOptions,
            new Dictionary<string, IReadOnlyDictionary<string, string>>());
        var driver = CSharpGeneratorDriver.Create(
            [new AdditionalAssemblyInfoGenerator().AsSourceGenerator()],
            parseOptions: new CSharpParseOptions(languageVersion),
            optionsProvider: optionsProvider);
        var compilation = TestCompilation.Create();
        var runResult = driver.RunGeneratorsAndUpdateCompilation(compilation, out var outputCompilation, out _).GetRunResult();
        var tree = runResult.GeneratedTrees.Single();
        return (tree.FilePath, tree.ToString().ReplaceLineEndings("\n"), outputCompilation);
    }
}
